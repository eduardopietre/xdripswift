#!/usr/bin/env bash
# Runs the platform-independent parts of xDrip4iOS on Linux with the open-source Swift toolchain.
#
# The real sources and XCTest files are copied into a throwaway SwiftPM package whose library
# module is called `xdrip`, so the unchanged `@testable import xdrip` in the tests keeps working.
# Which files go in is listed per suite in linux/suites/*.txt (format documented there and in
# CLAUDE.md). Nothing in the Xcode project is modified.
#
# Usage:
#   linux/xdrip-linux.sh test    [suite ...]                 # swift test for the suites (default: all)
#   linux/xdrip-linux.sh snippet <file.swift> [suite ...]    # run a script against the suites' sources
#   linux/xdrip-linux.sh list                                # list available suites
#
# Environment:
#   SWIFT_BIN          directory with the swift binary (default: /opt/swift/usr/bin, else PATH)
#   XDRIP_LINUX_BUILD  where the generated package lives (default: /tmp/xdrip-linux)
#   SWIFT_TEST_ARGS    extra arguments for `swift test`, e.g. "--filter Libre2"
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUITES_DIR="$ROOT/linux/suites"
SHIMS_DIR="$ROOT/linux/shims"
BUILD="${XDRIP_LINUX_BUILD:-/tmp/xdrip-linux}"

if [[ -x "${SWIFT_BIN:-/opt/swift/usr/bin}/swift" ]]; then
    export PATH="${SWIFT_BIN:-/opt/swift/usr/bin}:$PATH"
fi

die() { echo "error: $*" >&2; exit 1; }
trim() { local s="$1"; s="${s#"${s%%[![:space:]]*}"}"; s="${s%"${s##*[![:space:]]}"}"; printf '%s' "$s"; }

all_suites() { for f in "$SUITES_DIR"/*.txt; do basename "$f" .txt; done; }

# Copies one source into the package, flattening its path into a unique file name.
place() { # <repo-relative path> <destination dir>
    local src="$ROOT/$1" dest_dir="$2"
    [[ -f "$src" ]] || die "missing file: $1"
    local name; name="$(printf '%s' "$1" | tr '/ ' '__')"
    cp "$src" "$dest_dir/$name"
}

# Copies the lines from the first match of <start-regex> up to, not including, the first later
# match of <end-regex>. Used for files that mix pure Swift with Apple-only code.
extract() { # <repo-relative path> <start-regex> <end-regex> <destination dir>
    local src="$ROOT/$1" dest_dir="$4"
    [[ -f "$src" ]] || die "missing file: $1"
    local name; name="extract_$(printf '%s' "$1" | tr '/ ' '__')"
    awk -v s="$2" -v e="$3" '
        !on && $0 ~ s { on = 1 }
        on && done_start && $0 ~ e { exit }
        on { print; done_start = 1 }
    ' "$src" > "$dest_dir/$name"
    [[ -s "$dest_dir/$name" ]] || die "extract matched nothing in $1 (start: $2)"
    { echo "import Foundation"; cat "$dest_dir/$name"; } > "$dest_dir/$name.tmp" && mv "$dest_dir/$name.tmp" "$dest_dir/$name"
}

generate() { # <suite ...>
    rm -rf "$BUILD/Sources" "$BUILD/Tests"
    mkdir -p "$BUILD/Sources/xdrip" "$BUILD/Tests/xdripTests" "$BUILD/Sources/snippet"
    local lib="$BUILD/Sources/xdrip" tests="$BUILD/Tests/xdripTests"
    local suite line kind rest
    for suite in "$@"; do
        local file="$SUITES_DIR/$suite.txt"
        [[ -f "$file" ]] || die "unknown suite '$suite' (see: $0 list)"
        while IFS= read -r line || [[ -n "$line" ]]; do
            line="$(trim "${line%%#*}")"
            [[ -z "$line" ]] && continue
            kind="${line%%[[:space:]]*}"; rest="$(trim "${line#"$kind"}")"
            case "$kind" in
                src)  place "$rest" "$lib" ;;
                test) place "$rest" "$tests" ;;
                shim) [[ -f "$SHIMS_DIR/$rest" ]] || die "missing shim: $rest"; cp "$SHIMS_DIR/$rest" "$lib/shim_$rest" ;;
                extract)
                    IFS='|' read -r path start end <<< "$rest"
                    extract "$(trim "$path")" "$(trim "$start")" "$(trim "$end")" "$lib" ;;
                *) die "$suite.txt: unknown directive '$kind'" ;;
            esac
        done < "$file"
    done
    # A placeholder so the snippet target always exists; replaced by `snippet`.
    echo 'import xdrip' > "$BUILD/Sources/snippet/main.swift"

    cat > "$BUILD/Package.swift" <<'EOF'
// swift-tools-version:5.9
// Generated by linux/xdrip-linux.sh. Do not edit: it is rewritten on every run.
import PackageDescription

let package = Package(
    name: "xdrip-linux",
    targets: [
        .target(name: "xdrip", path: "Sources/xdrip",
                swiftSettings: [.unsafeFlags(["-enable-testing"])]),
        .executableTarget(name: "snippet", dependencies: ["xdrip"], path: "Sources/snippet"),
        .testTarget(name: "xdripTests", dependencies: ["xdrip"], path: "Tests/xdripTests"),
    ]
)
EOF
}

command -v swift >/dev/null || die "swift not found; run linux/install-swift.sh first"

cmd="${1:-test}"; shift || true
case "$cmd" in
    list) all_suites ;;
    test)
        [[ $# -gt 0 ]] || set -- $(all_suites)
        generate "$@"
        cd "$BUILD"
        # shellcheck disable=SC2086
        swift test ${SWIFT_TEST_ARGS:-}
        ;;
    snippet)
        [[ $# -ge 1 ]] || die "usage: $0 snippet <file.swift> [suite ...]"
        snippet="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"; shift
        [[ -f "$snippet" ]] || die "no such snippet: $snippet"
        [[ $# -gt 0 ]] || set -- $(all_suites)
        generate "$@"
        cp "$snippet" "$BUILD/Sources/snippet/main.swift"
        cd "$BUILD"
        swift run -q snippet
        ;;
    *) die "unknown command '$cmd' (test | snippet | list)" ;;
esac
